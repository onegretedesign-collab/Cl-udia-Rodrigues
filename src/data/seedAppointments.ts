function offsetWorkdayISO(baseDate: Date, workingDayOffset: number): string {
  const d = new Date(baseDate.getFullYear(), baseDate.getMonth(), baseDate.getDate());
  if (workingDayOffset === 0) {
    if (d.getDay() === 0) d.setDate(d.getDate() + 1);
    return getLocalTodayISO(d);
  }
  const step = workingDayOffset > 0 ? 1 : -1;
  let remaining = Math.abs(workingDayOffset);
  while (remaining > 0) {
    d.setDate(d.getDate() + step);
    if (d.getDay() !== 0) {
      remaining--;
    }
  }
  return getLocalTodayISO(d);
}

function sameMonthDayISO(baseDate: Date, dayOfMonth: number): string {
  const year = baseDate.getFullYear();
  const month = baseDate.getMonth();
  const maxDay = new Date(year, month + 1, 0).getDate();
  const safeDay = Math.min(dayOfMonth, maxDay);
  const d = new Date(year, month, safeDay);
  if (d.getDay() === 0) {
    d.setDate(safeDay > 1 ? safeDay - 1 : safeDay + 1);
  }
  return getLocalTodayISO(d);
}

